CREATE TABLE fulfillment_command_ids (
  command_id CHAR(36) NOT NULL,
  order_id BIGINT NOT NULL,
  PRIMARY KEY (command_id)
);

CREATE TABLE fulfillment_merchant_jobs (
  command_id CHAR(36) NOT NULL,
  order_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  operation VARCHAR(24) NOT NULL,
  expected_version BIGINT NOT NULL,
  carrier VARCHAR(100),
  tracking_number VARCHAR(120),
  detail VARCHAR(500),
  step VARCHAR(24) NOT NULL,
  status VARCHAR(20) NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  owner_token CHAR(36),
  lease_until TIMESTAMPTZ(6) NULL,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL,
  last_error VARCHAR(80),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (command_id)
);

CREATE INDEX idx_fulfillment_merchant_due ON fulfillment_merchant_jobs (status,next_attempt_at,command_id);
CREATE INDEX idx_fulfillment_merchant_operation ON fulfillment_merchant_jobs (order_id,operation,expected_version);

CREATE TABLE fulfillment_merchant_recoveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  command_id CHAR(36) NOT NULL,
  recovery_id CHAR(36) NOT NULL,
  operator_id BIGINT NOT NULL,
  step VARCHAR(24) NOT NULL,
  previous_error VARCHAR(80),
  reason VARCHAR(300) NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_fulfillment_merchant_recovery UNIQUE (command_id,recovery_id),
  CONSTRAINT fk_fulfillment_merchant_recovery_job FOREIGN KEY (command_id) REFERENCES fulfillment_merchant_jobs (command_id)
);

CREATE INDEX idx_fulfillment_merchant_recovery_history ON fulfillment_merchant_recoveries (command_id,id);

CREATE TABLE fulfillment_order_locks (
  order_id BIGINT NOT NULL,
  PRIMARY KEY (order_id)
);

CREATE TABLE fulfillment_runtime_mode (
  singleton_id SMALLINT NOT NULL,
  mode VARCHAR(16),
  PRIMARY KEY (singleton_id),
  CONSTRAINT fulfillment_runtime_mode_chk_1 CHECK ((singleton_id = 1))
);

CREATE TABLE fulfillment_shadow_quarantine (
  table_name VARCHAR(64) NOT NULL,
  row_key VARCHAR(64) NOT NULL,
  source_sequence BIGINT NOT NULL,
  reason VARCHAR(64) NOT NULL,
  payload JSONB NOT NULL,
  PRIMARY KEY (table_name,row_key)
);

CREATE TABLE fulfillment_shadow_watermark (
  singleton_id SMALLINT NOT NULL,
  generation BIGINT NOT NULL,
  source_sequence BIGINT NOT NULL,
  PRIMARY KEY (singleton_id)
);

CREATE TABLE fulfillment_shipment_jobs (
  order_id BIGINT NOT NULL,
  command_id CHAR(36) NOT NULL,
  merchant_id BIGINT NOT NULL,
  order_number VARCHAR(64) NOT NULL,
  carrier VARCHAR(100) NOT NULL,
  tracking_number VARCHAR(120) NOT NULL,
  step VARCHAR(32) NOT NULL,
  status VARCHAR(20) NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  owner_token CHAR(36),
  lease_until TIMESTAMPTZ(6) NULL,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL,
  last_error VARCHAR(300),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  package_lines TEXT,
  warehouse_id BIGINT,
  PRIMARY KEY (command_id),
  CONSTRAINT fulfillment_shipment_jobs_chk_1 CHECK (((package_lines is null) or package_lines IS JSON))
);

CREATE INDEX idx_fulfillment_shipment_due ON fulfillment_shipment_jobs (status,next_attempt_at,order_id);
CREATE INDEX idx_fulfillment_shipment_order ON fulfillment_shipment_jobs (order_id,created_at,command_id);

CREATE TABLE fulfillment_shipment_recoveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_id BIGINT NOT NULL,
  recovery_id CHAR(36) NOT NULL,
  command_id CHAR(36) NOT NULL,
  operator_id BIGINT NOT NULL,
  step VARCHAR(32) NOT NULL,
  previous_error VARCHAR(300),
  reason VARCHAR(300) NOT NULL,
  evidence VARCHAR(500) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_fulfillment_shipment_recovery UNIQUE (order_id,recovery_id)
);

CREATE INDEX idx_fulfillment_shipment_recovery_history ON fulfillment_shipment_recoveries (order_id,id);

CREATE VIEW fulfillment_shadow_rows AS
SELECT 'fulfillment_order_locks' AS table_name, CAST(order_id AS text) AS row_key,
  json_build_object(
    'order_id', order_id
  ) AS payload
FROM fulfillment_order_locks
UNION ALL
SELECT 'fulfillment_command_ids' AS table_name, CAST(command_id AS text) AS row_key,
  json_build_object(
    'command_id', command_id,
    'order_id', order_id
  ) AS payload
FROM fulfillment_command_ids
UNION ALL
SELECT 'fulfillment_shipment_jobs' AS table_name, CAST(command_id AS text) AS row_key,
  json_build_object(
    'order_id', order_id,
    'command_id', command_id,
    'merchant_id', merchant_id,
    'order_number', order_number,
    'carrier', carrier,
    'tracking_number', tracking_number,
    'step', step,
    'status', status,
    'attempts', attempts,
    'owner_token', owner_token,
    'lease_until', to_char(lease_until AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US'),
    'next_attempt_at', to_char(next_attempt_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US'),
    'last_error', last_error,
    'created_at', to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US'),
    'updated_at', to_char(updated_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')
  ) AS payload
FROM fulfillment_shipment_jobs
UNION ALL
SELECT 'fulfillment_merchant_jobs' AS table_name, CAST(command_id AS text) AS row_key,
  json_build_object(
    'command_id', command_id,
    'order_id', order_id,
    'merchant_id', merchant_id,
    'operation', operation,
    'expected_version', expected_version,
    'carrier', carrier,
    'tracking_number', tracking_number,
    'detail', detail,
    'step', step,
    'status', status,
    'attempts', attempts,
    'owner_token', owner_token,
    'lease_until', to_char(lease_until AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US'),
    'next_attempt_at', to_char(next_attempt_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US'),
    'last_error', last_error,
    'updated_at', to_char(updated_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')
  ) AS payload
FROM fulfillment_merchant_jobs
UNION ALL
SELECT 'fulfillment_shipment_recoveries' AS table_name, CAST(id AS text) AS row_key,
  json_build_object(
    'id', id,
    'order_id', order_id,
    'recovery_id', recovery_id,
    'command_id', command_id,
    'operator_id', operator_id,
    'step', step,
    'previous_error', previous_error,
    'reason', reason,
    'evidence', evidence,
    'created_at', to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')
  ) AS payload
FROM fulfillment_shipment_recoveries
UNION ALL
SELECT 'fulfillment_merchant_recoveries' AS table_name, CAST(id AS text) AS row_key,
  json_build_object(
    'id', id,
    'command_id', command_id,
    'recovery_id', recovery_id,
    'operator_id', operator_id,
    'step', step,
    'previous_error', previous_error,
    'reason', reason,
    'evidence', evidence,
    'created_at', to_char(created_at AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS.US')
  ) AS payload
FROM fulfillment_merchant_recoveries;
