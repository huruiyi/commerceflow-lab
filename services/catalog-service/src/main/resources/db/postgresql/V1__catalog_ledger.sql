CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  brief VARCHAR(300) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  price DECIMAL(12,2) NOT NULL,
  image_url VARCHAR(500) NOT NULL,
  thumbnail_url VARCHAR(500) NOT NULL,
  merchant_id BIGINT NOT NULL,
  lifecycle_status VARCHAR(20) NOT NULL,
  business_version BIGINT NOT NULL,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  create_request_id CHAR(36),
  create_fingerprint CHAR(64),
  listing_product_id BIGINT,
  monitor_profile JSONB,
  CONSTRAINT uk_catalog_merchant_creation UNIQUE (merchant_id,create_request_id),
  CONSTRAINT fk_catalog_listing_product FOREIGN KEY (listing_product_id) REFERENCES products(id),
  CONSTRAINT chk_catalog_product_status CHECK (lifecycle_status IN ('ACTIVE','INACTIVE'))
);

CREATE INDEX ix_catalog_listing_product ON products(listing_product_id,id);

CREATE TABLE product_translations (
  product_id BIGINT NOT NULL,
  locale VARCHAR(10) NOT NULL,
  name VARCHAR(160) NOT NULL,
  brief VARCHAR(300) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  PRIMARY KEY (product_id,locale),
  CONSTRAINT fk_catalog_translation_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE TABLE catalog_event_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id VARCHAR(100) NOT NULL,
  event_type VARCHAR(50) NOT NULL,
  aggregate_id BIGINT NOT NULL,
  schema_version INT NOT NULL,
  business_version BIGINT NOT NULL,
  occurred_at TIMESTAMPTZ(6) NOT NULL,
  correlation_id VARCHAR(100) NOT NULL,
  causation_id VARCHAR(100) NOT NULL,
  payload JSONB NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW',
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_error VARCHAR(500),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at TIMESTAMPTZ(6),
  search_indexed_at TIMESTAMPTZ(6),
  elasticsearch_indexed_at TIMESTAMPTZ(6),
  CONSTRAINT uk_catalog_service_event UNIQUE (event_id),
  CONSTRAINT chk_catalog_service_event_status CHECK (status IN ('NEW','RETRY','PUBLISHED','DEAD'))
);

CREATE INDEX ix_catalog_service_event_dispatch ON catalog_event_outbox(status,next_attempt_at);
CREATE INDEX ix_catalog_service_event_aggregate ON catalog_event_outbox(aggregate_id,business_version);
CREATE INDEX ix_catalog_search_pending ON catalog_event_outbox(search_indexed_at,id);
CREATE INDEX ix_catalog_elasticsearch_pending ON catalog_event_outbox(elasticsearch_indexed_at,id);

CREATE TABLE catalog_cutover_state (
  cutover_key VARCHAR(50) PRIMARY KEY,
  status VARCHAR(20) NOT NULL,
  source_version INT NOT NULL,
  product_count INT NOT NULL,
  translation_count INT NOT NULL,
  outbox_count INT NOT NULL DEFAULT 0,
  product_fingerprint NUMERIC(20,0) NOT NULL CHECK (product_fingerprint BETWEEN 0 AND 18446744073709551615),
  translation_fingerprint NUMERIC(20,0) NOT NULL CHECK (translation_fingerprint BETWEEN 0 AND 18446744073709551615),
  outbox_fingerprint NUMERIC(20,0) NOT NULL DEFAULT 0 CHECK (outbox_fingerprint BETWEEN 0 AND 18446744073709551615),
  completed_at TIMESTAMPTZ(6),
  CONSTRAINT chk_catalog_cutover_status CHECK (status IN ('RUNNING','COMPLETE','FAILED'))
);

CREATE TABLE catalog_search_state (
  singleton_id INT PRIMARY KEY,
  generation BIGINT NOT NULL,
  rebuild_requested BOOLEAN NOT NULL,
  rebuilt_at TIMESTAMPTZ(6)
);

CREATE TABLE catalog_search_documents (
  generation BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  locale VARCHAR(10) NOT NULL,
  merchant_id BIGINT NOT NULL,
  business_version BIGINT NOT NULL,
  name VARCHAR(160) NOT NULL,
  brief VARCHAR(300) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  searchable TEXT NOT NULL,
  unit_price DECIMAL(12,2) NOT NULL,
  PRIMARY KEY (generation,product_id,locale)
);

CREATE INDEX ix_catalog_search_shop_price ON catalog_search_documents(generation,merchant_id,unit_price,product_id);

CREATE TABLE catalog_elasticsearch_state (
  singleton_id INT PRIMARY KEY,
  generation BIGINT NOT NULL,
  catalog_generation BIGINT NOT NULL
);

CREATE TABLE catalog_product_skus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  code VARCHAR(64) COLLATE "C" NOT NULL,
  spec_key CHAR(64) COLLATE "C" NOT NULL,
  specifications JSONB NOT NULL,
  default_sku BOOLEAN NOT NULL,
  default_product_id BIGINT GENERATED ALWAYS AS (CASE WHEN default_sku THEN product_id END) STORED,
  unit_price DECIMAL(12,2),
  lifecycle_status VARCHAR(12),
  business_version BIGINT NOT NULL DEFAULT 1,
  request_id CHAR(36),
  create_fingerprint CHAR(64),
  stock_product_id BIGINT,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_catalog_sku_product FOREIGN KEY (product_id) REFERENCES products(id),
  CONSTRAINT uk_catalog_sku_default UNIQUE (default_product_id),
  CONSTRAINT uk_catalog_sku_request UNIQUE (merchant_id,request_id),
  CONSTRAINT uk_catalog_sku_stock UNIQUE (stock_product_id),
  CONSTRAINT ck_catalog_sku_kind CHECK (
    (default_sku AND unit_price IS NULL AND lifecycle_status IS NULL)
    OR (NOT default_sku AND unit_price IS NOT NULL AND unit_price>=0
        AND lifecycle_status IS NOT NULL AND lifecycle_status IN ('ACTIVE','INACTIVE'))
  )
);

CREATE UNIQUE INDEX uk_catalog_sku_code ON catalog_product_skus(merchant_id,lower(rtrim(code)));
CREATE UNIQUE INDEX uk_catalog_sku_specs ON catalog_product_skus(product_id,lower(spec_key));

CREATE VIEW catalog_monitor_attribute_values AS
SELECT p.id AS product_id, attributes.name, attributes.value
FROM products p
CROSS JOIN LATERAL (VALUES
  ('brand',lower(p.monitor_profile->>'brand')),
  ('screen size',trim_scale((p.monitor_profile->>'screenSizeInches')::numeric(5,1))::text),
  ('resolution',concat(p.monitor_profile->>'widthPixels',' × ',p.monitor_profile->>'heightPixels')),
  ('panel',lower(p.monitor_profile->>'panel')),
  ('refresh rate',p.monitor_profile->>'refreshRateHz')
) attributes(name,value)
WHERE p.monitor_profile IS NOT NULL
UNION ALL
SELECT p.id,'port',lower(ports.value)
FROM products p
CROSS JOIN LATERAL jsonb_array_elements_text(
  CASE WHEN jsonb_typeof(p.monitor_profile->'ports')='array' THEN p.monitor_profile->'ports' ELSE '[]'::jsonb END
) ports(value);
