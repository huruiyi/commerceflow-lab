-- Stable business identifiers keep the case- and accent-insensitive comparisons.
CREATE COLLATION inventory_identifier (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE inventory_warehouses (
  id BIGINT NOT NULL,
  code VARCHAR(40) COLLATE inventory_identifier NOT NULL,
  priority INT NOT NULL,
  enabled BOOLEAN NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_inventory_warehouse_code UNIQUE (code)
);

COMMENT ON COLUMN inventory_warehouses.id IS '稳定仓库编号';
COMMENT ON COLUMN inventory_warehouses.code IS '仓库业务代码';
COMMENT ON COLUMN inventory_warehouses.priority IS '选仓优先级，较小值优先';
COMMENT ON COLUMN inventory_warehouses.enabled IS '是否受理新预占';

CREATE TABLE product_inventory (
  product_id BIGINT NOT NULL,
  merchant_id BIGINT,
  product_name VARCHAR(160) NOT NULL,
  thumbnail_url VARCHAR(500) NOT NULL,
  unit_price DECIMAL(12, 2) NOT NULL,
  catalog_lifecycle_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  catalog_business_version BIGINT NOT NULL DEFAULT 1,
  stock_available INT NOT NULL,
  stock_reserved INT NOT NULL,
  stock_sold INT NOT NULL,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (product_id),
  CONSTRAINT chk_inventory_balances CHECK (((stock_available >= 0) and (stock_reserved >= 0) and (stock_sold >= 0))),
  CONSTRAINT chk_inventory_catalog_lifecycle CHECK ((catalog_lifecycle_status in ('ACTIVE', 'INACTIVE')))
);

CREATE INDEX idx_product_inventory_merchant ON product_inventory (merchant_id);

CREATE TABLE inventory_catalog_event_inbox (
  event_id VARCHAR(100) COLLATE inventory_identifier NOT NULL,
  product_id BIGINT NOT NULL,
  business_version BIGINT NOT NULL,
  payload_fingerprint CHAR(64) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING',
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  processed_at TIMESTAMPTZ(6) NULL,
  PRIMARY KEY (event_id),
  CONSTRAINT chk_inventory_catalog_event_status CHECK ((status in ('PROCESSING', 'APPLIED', 'STALE')))
);

CREATE INDEX idx_inventory_catalog_product ON inventory_catalog_event_inbox (product_id, business_version);

CREATE TABLE inventory_command_inbox (
  command_id VARCHAR(100) COLLATE inventory_identifier NOT NULL,
  command_type VARCHAR(24) NOT NULL,
  order_id BIGINT NOT NULL,
  payload_fingerprint CHAR(64) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PROCESSING',
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  processed_at TIMESTAMPTZ(6) NULL,
  rejection_message VARCHAR(300),
  PRIMARY KEY (command_id),
  CONSTRAINT chk_inventory_command_status CHECK ((((status in ('PROCESSING', 'SUCCEEDED')) and (rejection_message is null)) or ((status = 'REJECTED') and (command_type = 'RESERVE') and (rejection_message is not null)))),
  CONSTRAINT chk_inventory_command_type CHECK ((command_type in ('RESERVE', 'COMMIT', 'RELEASE', 'REFUND')))
);

CREATE INDEX idx_inventory_command_order ON inventory_command_inbox (order_id, created_at);

CREATE TABLE inventory_migration_state (
  migration_key VARCHAR(60) COLLATE inventory_identifier NOT NULL,
  status VARCHAR(20) NOT NULL,
  source_version INT NOT NULL,
  generation INT NOT NULL DEFAULT 0,
  source_fingerprint VARCHAR(500) NOT NULL,
  completed_at TIMESTAMPTZ(6) NULL,
  PRIMARY KEY (migration_key),
  CONSTRAINT chk_inventory_migration_status CHECK ((status in ('RUNNING', 'READY', 'FAILED', 'CUTOVER_COMPLETE')))
);

CREATE TABLE inventory_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  event_id VARCHAR(100) COLLATE inventory_identifier NOT NULL,
  order_id BIGINT,
  product_id BIGINT NOT NULL,
  movement_type VARCHAR(32) NOT NULL,
  quantity INT NOT NULL,
  available_after INT NOT NULL,
  reserved_after INT NOT NULL,
  sold_after INT NOT NULL,
  detail VARCHAR(300) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  warehouse_id BIGINT NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  CONSTRAINT uk_inventory_movement_event UNIQUE (event_id),
  CONSTRAINT fk_inventory_movement_product FOREIGN KEY (product_id) REFERENCES product_inventory (product_id)
);

CREATE INDEX idx_inventory_movement_order ON inventory_movements (order_id);
CREATE INDEX idx_inventory_movement_product ON inventory_movements (product_id);

COMMENT ON COLUMN inventory_movements.warehouse_id IS '流水归属仓，历史流水归入默认仓';

CREATE TABLE inventory_outbound_documents (
  outbound_id CHAR(36) COLLATE inventory_identifier NOT NULL,
  order_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  payload_fingerprint CHAR(64) NOT NULL,
  posted_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  warehouse_id BIGINT NOT NULL DEFAULT 1,
  PRIMARY KEY (outbound_id),
  CONSTRAINT fk_inventory_outbound_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory_warehouses (id)
);

CREATE INDEX idx_inventory_outbound_order ON inventory_outbound_documents (order_id);
CREATE INDEX idx_inventory_outbound_order_warehouse ON inventory_outbound_documents (order_id, warehouse_id);
CREATE INDEX fk_inventory_outbound_warehouse ON inventory_outbound_documents (warehouse_id);

COMMENT ON COLUMN inventory_outbound_documents.warehouse_id IS '实际出库仓库编号';

CREATE TABLE inventory_outbound_lines (
  outbound_id CHAR(36) COLLATE inventory_identifier NOT NULL,
  order_line_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  PRIMARY KEY (outbound_id, order_line_id),
  CONSTRAINT fk_inventory_outbound_document FOREIGN KEY (outbound_id) REFERENCES inventory_outbound_documents (outbound_id),
  CONSTRAINT chk_inventory_outbound_quantity CHECK ((quantity > 0))
);

CREATE TABLE inventory_outbound_event_outbox (
  event_id VARCHAR(100) COLLATE inventory_identifier NOT NULL,
  outbound_id CHAR(36) COLLATE inventory_identifier NOT NULL,
  order_line_id BIGINT NOT NULL,
  payload JSONB NOT NULL,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  published_at TIMESTAMPTZ(6) NULL,
  PRIMARY KEY (event_id),
  CONSTRAINT fk_inventory_outbound_event_line FOREIGN KEY (outbound_id, order_line_id) REFERENCES inventory_outbound_lines (outbound_id, order_line_id)
);

CREATE INDEX idx_inventory_outbound_event_pending ON inventory_outbound_event_outbox (published_at, next_attempt_at, event_id);
CREATE INDEX fk_inventory_outbound_event_line ON inventory_outbound_event_outbox (outbound_id, order_line_id);

CREATE TABLE inventory_reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  status VARCHAR(24) NOT NULL,
  version INT NOT NULL DEFAULT 0,
  reserved_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  committed_at TIMESTAMPTZ(6) NULL,
  released_at TIMESTAMPTZ(6) NULL,
  warehouse_id BIGINT NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  CONSTRAINT uk_inventory_reservation_order_product_warehouse UNIQUE (order_id, product_id, warehouse_id),
  CONSTRAINT fk_inventory_reservation_product FOREIGN KEY (product_id) REFERENCES product_inventory (product_id),
  CONSTRAINT fk_reservation_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory_warehouses (id),
  CONSTRAINT chk_inventory_reservation_quantity CHECK ((quantity > 0)),
  CONSTRAINT chk_inventory_reservation_status CHECK ((status in ('RESERVED', 'COMMITTED', 'RELEASED', 'REFUNDED')))
);

CREATE INDEX idx_inventory_reservation_product ON inventory_reservations (product_id);
CREATE INDEX fk_reservation_warehouse ON inventory_reservations (warehouse_id);

COMMENT ON COLUMN inventory_reservations.warehouse_id IS '初次分配时锁定的发货仓';

CREATE TABLE inventory_line_credits (
  case_id CHAR(36) COLLATE inventory_identifier NOT NULL,
  order_id BIGINT NOT NULL,
  order_line_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  kind VARCHAR(24) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  warehouse_id BIGINT,
  outbound_id CHAR(36) COLLATE inventory_identifier,
  PRIMARY KEY (case_id),
  CONSTRAINT fk_inventory_credit_outbound FOREIGN KEY (outbound_id) REFERENCES inventory_outbound_documents (outbound_id),
  CONSTRAINT fk_inventory_credit_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory_warehouses (id),
  CONSTRAINT inventory_line_credits_chk_1 CHECK (((quantity > 0) and (kind in ('BEFORE_SHIPMENT', 'RETURN'))))
);

CREATE INDEX idx_inventory_credit_order ON inventory_line_credits (order_id, kind, product_id, order_line_id);
CREATE INDEX fk_inventory_credit_warehouse ON inventory_line_credits (warehouse_id);
CREATE INDEX fk_inventory_credit_outbound ON inventory_line_credits (outbound_id);

COMMENT ON COLUMN inventory_line_credits.case_id IS '关联商城售后单，用于重试去重';
COMMENT ON COLUMN inventory_line_credits.order_id IS '原订单标识';
COMMENT ON COLUMN inventory_line_credits.order_line_id IS '原订单行标识';
COMMENT ON COLUMN inventory_line_credits.merchant_id IS '原订单行商家';
COMMENT ON COLUMN inventory_line_credits.product_id IS '原商品快照标识';
COMMENT ON COLUMN inventory_line_credits.quantity IS '恢复到可售库存的件数';
COMMENT ON COLUMN inventory_line_credits.kind IS 'BEFORE_SHIPMENT 或 RETURN';
COMMENT ON COLUMN inventory_line_credits.warehouse_id IS '回补仓，历史空值归入默认仓';
COMMENT ON COLUMN inventory_line_credits.outbound_id IS '退货关联的原出库单';

