CREATE FUNCTION touch_product_inventory() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW IS DISTINCT FROM OLD THEN
    NEW.updated_at := statement_timestamp();
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER product_inventory_updated_at
BEFORE UPDATE ON product_inventory
FOR EACH ROW EXECUTE FUNCTION touch_product_inventory();
