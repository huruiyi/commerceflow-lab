-- Preserve case- and accent-insensitive comparisons for stable business identifiers.
CREATE COLLATION order_identifier (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE EXTENSION unaccent;

CREATE TABLE shop_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_number VARCHAR(40) COLLATE order_identifier NOT NULL,
  customer_id BIGINT NOT NULL,
  status VARCHAR(40) NOT NULL,
  inventory_status VARCHAR(40) NOT NULL,
  total_amount DECIMAL(12, 2) NOT NULL,
  currency VARCHAR(3) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL,
  updated_at TIMESTAMPTZ(6) NOT NULL,
  confirmed_at TIMESTAMPTZ(6) NULL,
  shipped_at TIMESTAMPTZ(6) NULL,
  carrier VARCHAR(100),
  tracking_number VARCHAR(120),
  payment_due_at TIMESTAMPTZ(6) NOT NULL,
  cancelled_at TIMESTAMPTZ(6) NULL,
  cancel_reason VARCHAR(300),
  received_at TIMESTAMPTZ(6) NULL,
  completed_at TIMESTAMPTZ(6) NULL,
  logistics_delivered_at TIMESTAMPTZ(6) NULL,
  shipment_intent_key CHAR(64),
  shipment_version BIGINT NOT NULL DEFAULT 0,
  discount_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  shipping_fee DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  product_subtotal DECIMAL(12, 2) GENERATED ALWAYS AS (((total_amount + discount_amount) - shipping_fee)) STORED NOT NULL,
  coupon_id CHAR(36) COLLATE order_identifier,
  PRIMARY KEY (id),
  CONSTRAINT uk_shop_orders_number UNIQUE (order_number),
  CONSTRAINT ck_order_amount_snapshot CHECK (((total_amount >= 0) and (shipping_fee >= 0) and (discount_amount >= 0) and (product_subtotal >= discount_amount))),
  CONSTRAINT shop_orders_chk_1 CHECK (((coupon_id is null) or (discount_amount > 0)))
);

CREATE INDEX idx_order_coupon_id ON shop_orders (coupon_id);

COMMENT ON COLUMN shop_orders.shipment_intent_key IS '发货商家与运单参数的稳定指纹';
COMMENT ON COLUMN shop_orders.shipment_version IS '订单侧运单详情的最新已确认版本';
COMMENT ON COLUMN shop_orders.coupon_id IS '成交时冻结的顾客券实例';

CREATE TABLE order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  order_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  product_name VARCHAR(160) NOT NULL,
  thumbnail_url VARCHAR(500) NOT NULL,
  unit_price DECIMAL(12, 2) NOT NULL,
  quantity INT NOT NULL,
  subtotal DECIMAL(12, 2) NOT NULL,
  discount_amount DECIMAL(12, 2) NOT NULL DEFAULT 0.00,
  PRIMARY KEY (id),
  CONSTRAINT fk_shadow_item_order FOREIGN KEY (order_id) REFERENCES shop_orders (id) ON DELETE CASCADE,
  CONSTRAINT ck_order_item_discount CHECK (((discount_amount >= 0) and (discount_amount <= subtotal)))
);

CREATE INDEX idx_order_items_order ON order_items (order_id);

CREATE TABLE order_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
