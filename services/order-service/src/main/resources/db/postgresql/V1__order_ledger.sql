COMMENT ON COLUMN order_package_allocations.warehouse_id IS '包裹分配的原仓编号';

CREATE TABLE order_package_lines (
  package_id CHAR(36) COLLATE order_identifier NOT NULL,
  order_line_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  actual_quantity INT,
  PRIMARY KEY (package_id, order_line_id),
  CONSTRAINT fk_order_package_item FOREIGN KEY (order_line_id) REFERENCES order_items (id),
  CONSTRAINT fk_order_package_line FOREIGN KEY (package_id) REFERENCES order_package_allocations (package_id),
  CONSTRAINT chk_package_actual_quantity CHECK (((actual_quantity is null) or (actual_quantity between 0 and quantity))),
  CONSTRAINT order_package_lines_chk_1 CHECK ((quantity > 0))
);

CREATE INDEX idx_order_package_line ON order_package_lines (order_line_id, package_id);

COMMENT ON COLUMN order_package_lines.package_id IS '所属履约包裹标识';
COMMENT ON COLUMN order_package_lines.order_line_id IS '原订单行标识';
COMMENT ON COLUMN order_package_lines.quantity IS '该包裹分配的发货件数';

CREATE TABLE order_warehouse_amounts (
  order_id BIGINT NOT NULL,
  order_line_id BIGINT NOT NULL,
  warehouse_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  gross_amount DECIMAL(12, 2) NOT NULL,
  discount_amount DECIMAL(12, 2) NOT NULL,
  freight_amount DECIMAL(12, 2) NOT NULL,
  PRIMARY KEY (order_id, order_line_id, warehouse_id),
  CONSTRAINT fk_order_warehouse_item FOREIGN KEY (order_line_id) REFERENCES order_items (id),
  CONSTRAINT fk_order_warehouse_order FOREIGN KEY (order_id) REFERENCES shop_orders (id),
  CONSTRAINT order_warehouse_amounts_chk_1 CHECK (((quantity > 0) and (gross_amount >= discount_amount) and (discount_amount >= 0) and (freight_amount >= 0)))
);

CREATE INDEX fk_order_warehouse_item ON order_warehouse_amounts (order_line_id);

COMMENT ON COLUMN order_warehouse_amounts.order_id IS '该分配所属订单';
COMMENT ON COLUMN order_warehouse_amounts.order_line_id IS '原订单行编号';
COMMENT ON COLUMN order_warehouse_amounts.warehouse_id IS '库存服务确认的分配仓';
COMMENT ON COLUMN order_warehouse_amounts.quantity IS '分配到该仓的订单行件数';
COMMENT ON COLUMN order_warehouse_amounts.gross_amount IS '未扣优惠的商品金额';
COMMENT ON COLUMN order_warehouse_amounts.discount_amount IS '继承订单行的优惠份额';
COMMENT ON COLUMN order_warehouse_amounts.freight_amount IS '用于对账的原运费份额';

