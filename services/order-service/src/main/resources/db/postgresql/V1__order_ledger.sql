CREATE TABLE order_line_refund_admissions (
  case_id CHAR(36) COLLATE order_identifier NOT NULL,
  order_id BIGINT NOT NULL,
  order_line_id BIGINT NOT NULL,
  quantity INT NOT NULL,
  status VARCHAR(12) NOT NULL,
  warehouse_id BIGINT NOT NULL DEFAULT 1,
  PRIMARY KEY (case_id),
  CONSTRAINT fk_line_refund_item FOREIGN KEY (order_line_id) REFERENCES order_items (id),
  CONSTRAINT fk_line_refund_order FOREIGN KEY (order_id) REFERENCES shop_orders (id),
  CONSTRAINT order_line_refund_admissions_chk_1 CHECK (((quantity > 0) and (status in ('HELD', 'SETTLED', 'RELEASED'))))
);

CREATE INDEX idx_line_refund_order_status ON order_line_refund_admissions (order_id, status, order_line_id);
CREATE INDEX fk_line_refund_item ON order_line_refund_admissions (order_line_id);

COMMENT ON COLUMN order_line_refund_admissions.case_id IS '售后单的稳定标识';
COMMENT ON COLUMN order_line_refund_admissions.order_id IS '需要核对发货意图的原订单';
COMMENT ON COLUMN order_line_refund_admissions.order_line_id IS '原订单行标识';
COMMENT ON COLUMN order_line_refund_admissions.quantity IS '锁定或已退款的件数';
COMMENT ON COLUMN order_line_refund_admissions.status IS 'HELD、SETTLED 或 RELEASED';
COMMENT ON COLUMN order_line_refund_admissions.warehouse_id IS '未发退款释放的原仓编号';

CREATE TABLE order_package_allocations (
  package_id CHAR(36) COLLATE order_identifier NOT NULL,
  order_id BIGINT NOT NULL,
  merchant_id BIGINT NOT NULL,
  carrier VARCHAR(100) NOT NULL,
  tracking_number VARCHAR(120) NOT NULL,
