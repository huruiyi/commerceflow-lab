-- Match case- and accent-insensitive comparisons for existing business identifiers.
CREATE COLLATION payment_identifier_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE payment_merchant_accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  channel varchar(30) COLLATE payment_identifier_ci NOT NULL,
  merchant_no varchar(64) COLLATE payment_identifier_ci NOT NULL,
  app_id varchar(64) COLLATE payment_identifier_ci NOT NULL,
  display_name varchar(100) COLLATE payment_identifier_ci NOT NULL,
  signing_algorithm varchar(30) COLLATE payment_identifier_ci NOT NULL,
  api_secret varchar(160) COLLATE payment_identifier_ci NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_payment_merchant_channel UNIQUE (channel),
  CONSTRAINT uk_payment_merchant_number UNIQUE (merchant_no)
);

CREATE TABLE payment_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  order_id bigint NOT NULL,
  payment_number varchar(40) COLLATE payment_identifier_ci NOT NULL,
  idempotency_key varchar(80) COLLATE payment_identifier_ci NOT NULL,
  amount decimal(12,2) NOT NULL,
  status varchar(30) COLLATE payment_identifier_ci NOT NULL,
  failure_reason varchar(200) COLLATE payment_identifier_ci NOT NULL,
  created_at timestamp(6) without time zone NOT NULL,
  merchant_account_id bigint,
  channel varchar(30) COLLATE payment_identifier_ci NOT NULL,
  currency varchar(3) COLLATE payment_identifier_ci NOT NULL,
  request_fingerprint varchar(64) COLLATE payment_identifier_ci NOT NULL,
  channel_transaction_no varchar(80) COLLATE payment_identifier_ci,
  paid_at timestamp(6) without time zone,
  expires_at timestamp(6) without time zone,
  updated_at timestamp(6) without time zone NOT NULL,
  checkout_url varchar(500) COLLATE payment_identifier_ci,
  action_type varchar(30) COLLATE payment_identifier_ci,
  qr_payload varchar(500) COLLATE payment_identifier_ci,
  version int NOT NULL,
  refunded_amount decimal(12,2) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_payment_number UNIQUE (payment_number),
  CONSTRAINT uk_payment_idempotency UNIQUE (idempotency_key),
  CONSTRAINT uk_payment_channel_transaction UNIQUE (channel, channel_transaction_no),
  CONSTRAINT uk_payment_merchant_idempotency UNIQUE (merchant_account_id, idempotency_key),
  CONSTRAINT fk_shadow_payment_merchant FOREIGN KEY (merchant_account_id) REFERENCES payment_merchant_accounts (id)
);
CREATE INDEX idx_payment_order ON payment_records (order_id);

CREATE TABLE refund_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  refund_number varchar(40) COLLATE payment_identifier_ci NOT NULL,
  order_id bigint NOT NULL,
  payment_id bigint NOT NULL,
  customer_id bigint NOT NULL,
  idempotency_key varchar(80) COLLATE payment_identifier_ci NOT NULL,
  request_fingerprint varchar(64) COLLATE payment_identifier_ci NOT NULL,
  amount decimal(12,2) NOT NULL,
  currency varchar(3) COLLATE payment_identifier_ci NOT NULL,
  reason_code varchar(50) COLLATE payment_identifier_ci NOT NULL,
  reason_detail varchar(500) COLLATE payment_identifier_ci NOT NULL,
  status varchar(30) COLLATE payment_identifier_ci NOT NULL,
  inventory_status varchar(40) COLLATE payment_identifier_ci NOT NULL,
  order_status_before_refund varchar(40) COLLATE payment_identifier_ci NOT NULL,
  channel_refund_no varchar(100) COLLATE payment_identifier_ci,
  failure_reason varchar(300) COLLATE payment_identifier_ci NOT NULL,
  requested_at timestamp(6) without time zone NOT NULL,
  succeeded_at timestamp(6) without time zone,
  failed_at timestamp(6) without time zone,
  created_at timestamp(6) without time zone NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL,
  version int NOT NULL,
  after_sale_id char(36) COLLATE payment_identifier_ci,
  PRIMARY KEY (id),
  CONSTRAINT uk_refund_number UNIQUE (refund_number),
  CONSTRAINT uk_refund_idempotency UNIQUE (payment_id, idempotency_key),
  CONSTRAINT uk_refund_channel_no UNIQUE (channel_refund_no),
  CONSTRAINT uk_refund_after_sale UNIQUE (after_sale_id),
  CONSTRAINT fk_shadow_refund_payment FOREIGN KEY (payment_id) REFERENCES payment_records (id),
  CONSTRAINT chk_shadow_refund_amount CHECK ((amount > 0)),
  CONSTRAINT chk_shadow_refund_inventory CHECK ((inventory_status in ('NOT_STARTED','WAITING','REFUNDED','RECONCILIATION_REQUIRED')))
);
CREATE INDEX idx_refund_order ON refund_records (order_id);
CREATE INDEX idx_refund_customer ON refund_records (customer_id);
COMMENT ON COLUMN refund_records.after_sale_id IS '商城订单行售后标识';

