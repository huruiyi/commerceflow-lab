-- Preserve case- and accent-insensitive equality for business identifiers.
CREATE COLLATION notification_identifier (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE customer_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  event_id VARCHAR(100) COLLATE notification_identifier NOT NULL,
  customer_id BIGINT NOT NULL,
  order_id BIGINT NULL,
  notification_type VARCHAR(50) NOT NULL,
  title VARCHAR(160) NOT NULL,
  message VARCHAR(500) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'UNREAD',
  read_at TIMESTAMPTZ(6) NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_notification_event UNIQUE (event_id)
);

CREATE TABLE notification_inbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  consumer_name VARCHAR(100) COLLATE notification_identifier NOT NULL,
  event_id VARCHAR(100) COLLATE notification_identifier NOT NULL,
  event_type VARCHAR(80) NOT NULL,
  schema_version INT NOT NULL,
  correlation_id VARCHAR(100) NOT NULL,
  causation_id VARCHAR(100) NOT NULL,
  traceparent VARCHAR(55) NOT NULL,
  processed_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_notification_inbox_consumer_event UNIQUE (consumer_name, event_id)
);

CREATE TABLE notification_delivery_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  event_id VARCHAR(100) COLLATE notification_identifier NOT NULL,
  topic VARCHAR(100) NOT NULL,
  payload JSONB NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW',
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  last_error VARCHAR(500) NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  published_at TIMESTAMPTZ(6) NULL,
  processed_at TIMESTAMPTZ(6) NULL,
  PRIMARY KEY (id),
  CONSTRAINT uk_notification_delivery_event UNIQUE (event_id)
);

CREATE TABLE notification_storage_state (
  id SMALLINT NOT NULL,
  source_watermark BIGINT NOT NULL DEFAULT 0,
  backfill_completed BOOLEAN NOT NULL DEFAULT FALSE,
  completed_at TIMESTAMPTZ(6) NULL,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT ck_notification_storage_state_singleton CHECK (id=1)
);

INSERT INTO notification_storage_state(id) VALUES(1);

CREATE TABLE notification_storage_audits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  matched_count INT NOT NULL,
  missing_count INT NOT NULL,
  orphan_count INT NOT NULL,
  mismatch_count INT NOT NULL,
  backfill_completed BOOLEAN NOT NULL,
  passed BOOLEAN NOT NULL,
  checked_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id)
);

CREATE TABLE notification_storage_quarantine (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  original_notification_id BIGINT NOT NULL,
  event_id VARCHAR(100) COLLATE notification_identifier NOT NULL,
  customer_id BIGINT NOT NULL,
  order_id BIGINT NULL,
  notification_type VARCHAR(50) NOT NULL,
  title VARCHAR(160) NOT NULL,
  message VARCHAR(500) NOT NULL,
  status VARCHAR(20) NOT NULL,
  read_at TIMESTAMPTZ(6) NULL,
  created_at TIMESTAMPTZ(6) NOT NULL,
  reason VARCHAR(100) NOT NULL,
  quarantined_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_notification_quarantine_event UNIQUE (event_id)
);

CREATE TABLE offsite_notification_inbox (
  event_id VARCHAR(120) COLLATE notification_identifier PRIMARY KEY,
  event_type VARCHAR(40) NOT NULL,
  recipient_id BIGINT NOT NULL,
  order_id BIGINT NOT NULL,
  reference VARCHAR(100) NOT NULL,
  fingerprint CHAR(64) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6)
);

CREATE TABLE offsite_notification_deliveries (
  request_id CHAR(36) COLLATE notification_identifier PRIMARY KEY,
  event_id VARCHAR(120) COLLATE notification_identifier NOT NULL,
  channel VARCHAR(10) NOT NULL,
  recipient VARCHAR(120) NOT NULL,
  subject VARCHAR(160) NULL,
  message VARCHAR(400) NOT NULL,
  status VARCHAR(16) NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  provider_id CHAR(36) NULL,
  last_error VARCHAR(100) NULL,
  lease CHAR(36) NULL,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  CONSTRAINT uk_offsite_channel UNIQUE(event_id, channel),
  CONSTRAINT fk_offsite_delivery_event FOREIGN KEY (event_id) REFERENCES offsite_notification_inbox(event_id),
  CONSTRAINT chk_offsite_delivery_channel CHECK (channel IN ('SMS','EMAIL')),
  CONSTRAINT chk_offsite_delivery_status CHECK (status IN ('PENDING','RETRY','ACCEPTED','DELIVERED','FAILED','SKIPPED'))
);

CREATE INDEX ix_notification_customer_created ON customer_notifications (customer_id, created_at);
CREATE INDEX ix_notification_delivery_dispatch ON notification_delivery_outbox (status, next_attempt_at);
CREATE INDEX ix_notification_storage_audit_time ON notification_storage_audits (checked_at);
CREATE INDEX idx_offsite_due ON offsite_notification_deliveries (status, next_attempt_at, request_id);

