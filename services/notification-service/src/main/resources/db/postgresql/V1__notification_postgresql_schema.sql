CREATE FUNCTION touch_notification_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at AND NEW IS DISTINCT FROM OLD THEN
    NEW.updated_at := statement_timestamp();
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER touch_storage_state_updated_at BEFORE UPDATE ON notification_storage_state
FOR EACH ROW EXECUTE FUNCTION touch_notification_updated_at();

CREATE TRIGGER touch_offsite_delivery_updated_at BEFORE UPDATE ON offsite_notification_deliveries
FOR EACH ROW EXECUTE FUNCTION touch_notification_updated_at();
