CREATE TABLE reference_datasets (
  dataset_key VARCHAR(64) PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  current_release_id BIGINT
);

CREATE TABLE reference_releases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_key VARCHAR(64) NOT NULL REFERENCES reference_datasets(dataset_key),
  version VARCHAR(64) NOT NULL,
  source_url VARCHAR(500) NOT NULL,
  source_revision VARCHAR(160) NOT NULL,
  sha256 CHAR(64) NOT NULL,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at TIMESTAMPTZ,
  row_count INTEGER NOT NULL DEFAULT 0 CHECK (row_count >= 0),
  UNIQUE (dataset_key, version),
  UNIQUE (dataset_key, id)
);

ALTER TABLE reference_datasets
  ADD CONSTRAINT fk_reference_current_release
  FOREIGN KEY (dataset_key, current_release_id) REFERENCES reference_releases(dataset_key, id);

CREATE TABLE reference_nodes (
  release_id BIGINT NOT NULL REFERENCES reference_releases(id),
  code VARCHAR(64) NOT NULL,
  parent_code VARCHAR(64),
  level SMALLINT NOT NULL CHECK (level BETWEEN 1 AND 5),
  name VARCHAR(200) NOT NULL,
  PRIMARY KEY (release_id, code),
  FOREIGN KEY (release_id, parent_code) REFERENCES reference_nodes(release_id, code)
    DEFERRABLE INITIALLY DEFERRED,
  CHECK ((level = 1 AND parent_code IS NULL) OR (level > 1 AND parent_code IS NOT NULL))
);

CREATE INDEX ix_reference_children ON reference_nodes(release_id, parent_code, code);

CREATE TABLE reference_publications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_key VARCHAR(64) NOT NULL,
  release_id BIGINT NOT NULL,
  previous_release_id BIGINT,
  published_by BIGINT NOT NULL,
  published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (dataset_key, release_id) REFERENCES reference_releases(dataset_key, id),
  FOREIGN KEY (dataset_key, previous_release_id) REFERENCES reference_releases(dataset_key, id)
);

