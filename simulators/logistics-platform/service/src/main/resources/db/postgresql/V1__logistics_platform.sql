-- Preserve case- and accent-insensitive comparisons on external shipment references and nonce keys.
CREATE COLLATION logistics_identifier (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE shipment_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  merchant_shipment_no VARCHAR(100) COLLATE logistics_identifier NOT NULL UNIQUE,
  platform_shipment_no VARCHAR(100) COLLATE logistics_identifier NOT NULL UNIQUE,
  order_number VARCHAR(64) COLLATE logistics_identifier NOT NULL,
  carrier VARCHAR(100) COLLATE logistics_identifier NOT NULL,
  tracking_number VARCHAR(120) COLLATE logistics_identifier NOT NULL,
  status VARCHAR(40) COLLATE logistics_identifier NOT NULL,
  resume_status VARCHAR(40),
  callback_url VARCHAR(500) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  shipment_version BIGINT NOT NULL DEFAULT 0,
  test_callback_result VARCHAR(16) CHECK (test_callback_result IN ('ACCEPT','REJECT')),
  UNIQUE (carrier,tracking_number)
);
CREATE INDEX idx_shipment_auto_progress ON shipment_records(status,updated_at,id);

CREATE TABLE shipment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id BIGINT NOT NULL REFERENCES shipment_records(id),
  event_id VARCHAR(36) COLLATE logistics_identifier NOT NULL UNIQUE,
  event_type VARCHAR(30) NOT NULL DEFAULT 'PROGRESS',
  status VARCHAR(40) NOT NULL,
  location VARCHAR(160) NOT NULL,
  description VARCHAR(300) NOT NULL,
  occurred_at TIMESTAMPTZ(6) NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_shipment_events_timeline ON shipment_events(shipment_id,occurred_at,id);

CREATE TABLE signed_request_nonces (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_id VARCHAR(100) COLLATE logistics_identifier NOT NULL,
  nonce VARCHAR(100) COLLATE logistics_identifier NOT NULL,
  request_timestamp BIGINT NOT NULL,
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (app_id,nonce)
);

CREATE TABLE callback_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id BIGINT NOT NULL REFERENCES shipment_records(id),
  event_id VARCHAR(36) COLLATE logistics_identifier NOT NULL UNIQUE REFERENCES shipment_events(event_id),
  callback_url VARCHAR(500) NOT NULL,
  payload JSON NOT NULL,
  status VARCHAR(20) COLLATE logistics_identifier NOT NULL DEFAULT 'NEW',
  attempts INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL,
  next_attempt_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lease_until TIMESTAMPTZ(6),
  claimed_by VARCHAR(100),
  last_error VARCHAR(1000),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  published_at TIMESTAMPTZ(6),
  updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (attempts >= 0 AND max_attempts > 0)
);
CREATE INDEX idx_callback_outbox_dispatch ON callback_outbox(status,next_attempt_at,lease_until,id);
CREATE INDEX idx_callback_outbox_shipment ON callback_outbox(shipment_id,id);

CREATE TABLE callback_outbox_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outbox_id BIGINT NOT NULL REFERENCES callback_outbox(id),
  event_type VARCHAR(40) NOT NULL,
  from_status VARCHAR(20),
  to_status VARCHAR(20) NOT NULL,
  operated_by VARCHAR(160) NOT NULL,
  reason VARCHAR(500),
  created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_callback_outbox_events ON callback_outbox_events(outbox_id,created_at,id);
