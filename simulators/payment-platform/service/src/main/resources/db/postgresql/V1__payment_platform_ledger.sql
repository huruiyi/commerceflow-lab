-- Match case- and accent-insensitive comparisons for existing business identifiers.
CREATE COLLATION payment_identifier_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

CREATE TABLE payment_admin_user (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  username varchar(64) COLLATE payment_identifier_ci NOT NULL,
  password_hash varchar(255) COLLATE payment_identifier_ci NOT NULL,
  display_name varchar(100) COLLATE payment_identifier_ci NOT NULL,
  email varchar(128) COLLATE payment_identifier_ci NOT NULL,
  mobile varchar(32) COLLATE payment_identifier_ci,
  status varchar(32) COLLATE payment_identifier_ci NOT NULL DEFAULT 'ACTIVE',
  account_locked boolean NOT NULL DEFAULT false,
  login_failure_count int NOT NULL DEFAULT 0,
  locked_until timestamp(6) without time zone,
  password_change_required boolean NOT NULL DEFAULT false,
  mfa_required boolean NOT NULL DEFAULT false,
  mfa_enabled boolean NOT NULL DEFAULT false,
  last_login_at timestamp(6) without time zone,
  created_by bigint,
  created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_by bigint,
  updated_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_payment_admin_username UNIQUE (username),
  CONSTRAINT uk_payment_admin_email UNIQUE (email)
);

CREATE TABLE payment_admin_role (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  role_code varchar(64) COLLATE payment_identifier_ci NOT NULL,
  role_name varchar(100) COLLATE payment_identifier_ci NOT NULL,
  role_scope varchar(16) COLLATE payment_identifier_ci NOT NULL DEFAULT 'PLATFORM',
  description varchar(255) COLLATE payment_identifier_ci NOT NULL DEFAULT '',
  enabled boolean NOT NULL DEFAULT true,
  revision bigint NOT NULL DEFAULT 0,
  system_role boolean NOT NULL DEFAULT false,
  PRIMARY KEY (id),
  CONSTRAINT uk_payment_admin_role_code UNIQUE (role_code)
);
COMMENT ON COLUMN payment_admin_role.role_scope IS '平台角色或商户角色';
COMMENT ON COLUMN payment_admin_role.description IS '角色说明';
COMMENT ON COLUMN payment_admin_role.enabled IS '角色是否全局生效';
COMMENT ON COLUMN payment_admin_role.revision IS '角色权限版本';
COMMENT ON COLUMN payment_admin_role.system_role IS '受保护的内置角色';

CREATE TABLE payment_admin_user_role (
  user_id bigint NOT NULL,
  role_id bigint NOT NULL,
  enabled boolean NOT NULL DEFAULT true,
  PRIMARY KEY (user_id, role_id),
  CONSTRAINT fk_payment_admin_user_role_role FOREIGN KEY (role_id) REFERENCES payment_admin_role (id),
  CONSTRAINT fk_payment_admin_user_role_user FOREIGN KEY (user_id) REFERENCES payment_admin_user (id) ON DELETE CASCADE
);
CREATE INDEX fk_payment_admin_user_role_role ON payment_admin_user_role (role_id);
COMMENT ON COLUMN payment_admin_user_role.enabled IS '账号的角色绑定是否生效';

CREATE TABLE payment_merchant (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  merchant_no varchar(64) COLLATE payment_identifier_ci NOT NULL,
  display_name varchar(100) COLLATE payment_identifier_ci NOT NULL,
  app_id varchar(64) COLLATE payment_identifier_ci NOT NULL,
  secret_cipher varchar(512) COLLATE payment_identifier_ci NOT NULL,
  secret_last_four varchar(4) COLLATE payment_identifier_ci NOT NULL,
  credential_version int NOT NULL DEFAULT 1,
  signing_algorithm varchar(32) COLLATE payment_identifier_ci NOT NULL DEFAULT 'HMAC_SHA256',
  merchant_public_key text,
  notify_url varchar(500) COLLATE payment_identifier_ci,
  enabled boolean NOT NULL DEFAULT true,
  created_by bigint NOT NULL,
  created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_by bigint NOT NULL,
  updated_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  remark varchar(1000) COLLATE payment_identifier_ci NOT NULL DEFAULT '',
  PRIMARY KEY (id),
  CONSTRAINT uk_payment_merchant_no UNIQUE (merchant_no),
  CONSTRAINT uk_payment_merchant_app_id UNIQUE (app_id),
  CONSTRAINT fk_payment_merchant_creator FOREIGN KEY (created_by) REFERENCES payment_admin_user (id)
);
CREATE INDEX fk_payment_merchant_creator ON payment_merchant (created_by);
COMMENT ON COLUMN payment_merchant.merchant_no IS '支付平台分配的商户号';
COMMENT ON COLUMN payment_merchant.app_id IS '签名请求使用的应用标识';
COMMENT ON COLUMN payment_merchant.secret_cipher IS '加密存储的 HMAC 商户密钥';
COMMENT ON COLUMN payment_merchant.credential_version IS '当前签名凭据版本';
COMMENT ON COLUMN payment_merchant.signing_algorithm IS '商户请求签名算法';
COMMENT ON COLUMN payment_merchant.merchant_public_key IS 'RSA 签名商户公钥，HMAC 商户为空';
COMMENT ON COLUMN payment_merchant.notify_url IS '支付和退款结果默认回调地址';
COMMENT ON COLUMN payment_merchant.enabled IS '商户是否允许发起新请求';
COMMENT ON COLUMN payment_merchant.remark IS '商户中英文名称与用途备注';

