CREATE TABLE channel_payouts (
  attempt_id char(36) COLLATE payment_identifier_ci NOT NULL,
  statement_id char(36) COLLATE payment_identifier_ci NOT NULL,
  beneficiary_id bigint NOT NULL,
  amount decimal(16,2) NOT NULL,
  currency char(3) COLLATE payment_identifier_ci NOT NULL,
  channel_payout_no varchar(50) COLLATE payment_identifier_ci NOT NULL,
  status varchar(16) COLLATE payment_identifier_ci NOT NULL,
  simulate_failure boolean NOT NULL,
  created_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  resolved_at timestamp(6) without time zone,
  notified_at timestamp(6) without time zone,
  next_notify_at timestamp(6) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  active_statement_id char(36) COLLATE payment_identifier_ci GENERATED ALWAYS AS ((case when (status in ('PENDING','SUCCEEDED')) then statement_id end)) STORED,
  PRIMARY KEY (attempt_id),
  CONSTRAINT channel_payout_no UNIQUE (channel_payout_no),
  CONSTRAINT uk_channel_payout_active_statement UNIQUE (active_statement_id),
  CONSTRAINT ck_channel_payout_amount CHECK (((amount > 0) and (currency = 'CNY'))),
  CONSTRAINT ck_channel_payout_status CHECK ((status in ('PENDING','SUCCEEDED','FAILED')))
);
CREATE INDEX ix_payout_notify ON channel_payouts (status, notified_at, next_notify_at);
COMMENT ON COLUMN channel_payouts.attempt_id IS 'Merchant attempt idempotency key';
COMMENT ON COLUMN channel_payouts.statement_id IS 'Original frozen settlement statement';
COMMENT ON COLUMN channel_payouts.beneficiary_id IS 'Merchant store entitled to payment';
COMMENT ON COLUMN channel_payouts.status IS 'PENDING, SUCCEEDED or FAILED';

CREATE FUNCTION reject_payment_audit_changes() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'audit log is append-only';
END;
$$;

CREATE TRIGGER payment_audit_no_change BEFORE UPDATE OR DELETE ON payment_admin_audit_log
FOR EACH ROW EXECUTE FUNCTION reject_payment_audit_changes();
