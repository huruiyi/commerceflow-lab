START TRANSACTION WITH CONSISTENT SNAPSHOT, READ ONLY;

SELECT 'ORDER_SHIPMENT_INTENTS_OPEN', COUNT(*)
FROM shop_orders WHERE shipment_intent_key IS NOT NULL;

SELECT 'ORDER_SHIPMENT_INTENTS_INVALID_STATE', COUNT(*)
FROM shop_orders WHERE shipment_intent_key IS NOT NULL
  AND (status <> 'CONFIRMED' OR inventory_status <> 'COMMITTED');

COMMIT;
