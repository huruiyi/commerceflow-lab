CREATE TABLE scheduled_task_policies (
  task_type VARCHAR(64) NOT NULL,
  enabled BOOLEAN NOT NULL,
  primary_trigger VARCHAR(20) NOT NULL,
  reconciliation_enabled BOOLEAN NOT NULL,
  grace_period_seconds BIGINT NOT NULL,
  claim_lease_seconds BIGINT NOT NULL,
  max_attempts INT NOT NULL,
  retry_delay_seconds BIGINT NOT NULL,
  config_version BIGINT NOT NULL DEFAULT 1,
  updated_by VARCHAR(190) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (task_type),
  CONSTRAINT chk_scheduled_policy_trigger CHECK (primary_trigger IN ('DATABASE','RABBITMQ','ROCKETMQ')),
  CONSTRAINT chk_scheduled_policy_grace CHECK (grace_period_seconds >= 0),
  CONSTRAINT chk_scheduled_policy_lease CHECK (claim_lease_seconds > 0),
  CONSTRAINT chk_scheduled_policy_attempts CHECK (max_attempts > 0),
  CONSTRAINT chk_scheduled_policy_retry CHECK (retry_delay_seconds >= 0)
);

CREATE TABLE scheduled_tasks (
  id BIGINT NOT NULL AUTO_INCREMENT,
  task_key VARCHAR(128) NOT NULL,
  task_type VARCHAR(64) NOT NULL,
  aggregate_type VARCHAR(64) NOT NULL,
  aggregate_id VARCHAR(128) NOT NULL,
  payload_json JSON NOT NULL,
  status VARCHAR(24) NOT NULL,
  due_at TIMESTAMP(6) NOT NULL,
  primary_trigger_snapshot VARCHAR(20) NOT NULL,
  reconciliation_enabled_snapshot BOOLEAN NOT NULL,
  grace_period_seconds_snapshot BIGINT NOT NULL,
  claim_lease_seconds_snapshot BIGINT NOT NULL,
  max_attempts INT NOT NULL,
  retry_delay_seconds_snapshot BIGINT NOT NULL,
  policy_version_snapshot BIGINT NOT NULL,
  attempts INT NOT NULL DEFAULT 0,
  lease_until TIMESTAMP(6) NULL,
  claimed_by VARCHAR(190) NULL,
  last_trigger_source VARCHAR(32) NULL,
  last_error VARCHAR(1000) NULL,
  completed_at TIMESTAMP(6) NULL,
  cancelled_at TIMESTAMP(6) NULL,
  version INT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT uk_scheduled_task_key UNIQUE (task_type, task_key),
  CONSTRAINT chk_scheduled_task_status CHECK (status IN ('CREATED','SCHEDULED','PROCESSING','SUCCEEDED','FAILED','CANCELLED')),
  CONSTRAINT chk_scheduled_task_trigger CHECK (primary_trigger_snapshot IN ('DATABASE','RABBITMQ','ROCKETMQ')),
  INDEX idx_scheduled_task_due (primary_trigger_snapshot, status, due_at),
  INDEX idx_scheduled_task_reconcile (reconciliation_enabled_snapshot, status, due_at),
  INDEX idx_scheduled_task_aggregate (aggregate_type, aggregate_id),
  INDEX idx_scheduled_task_lease (status, lease_until)
);

CREATE TABLE scheduled_task_events (
  id BIGINT NOT NULL AUTO_INCREMENT,
  task_id BIGINT NOT NULL,
  event_type VARCHAR(40) NOT NULL,
  trigger_source VARCHAR(32) NOT NULL,
  from_status VARCHAR(24) NULL,
  to_status VARCHAR(24) NULL,
  detail VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  CONSTRAINT fk_scheduled_task_event_task FOREIGN KEY (task_id) REFERENCES scheduled_tasks(id) ON DELETE CASCADE,
  INDEX idx_scheduled_task_event_task (task_id, created_at)
);
